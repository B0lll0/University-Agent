def build_study_plans_markdown() -> str:
    """Compile all 11 MSA faculties and their 4/5-year study plans into Markdown for ChromaDB RAG indexing."""
    blocks: List[str] = ["# MSA University Complete Faculties, Majors, and 4/5 Year Study Plans\n"]
    for fac in MSA_FACULTIES_DATA.values():
        blocks.append(f"## Faculty of {fac['label_en']} ({fac['duration_en']})\n{fac['partner_en']}\n")
        for major in fac["majors"]:
            blocks.append(f"### {major['plan_title_en']}")
            for y in major["years_en"]:
                blocks.append(f"• {y}")
            blocks.append("")
    return "\n".join(blocks).strip() + "\n"
